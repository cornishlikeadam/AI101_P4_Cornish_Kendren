export function sprintMd(ws: Workspace, s: Sprint) {
  const gates = sprintGates(ws, s);
  return `## ${s.code}: ${s.title}\n\nStage ${s.stage} · status ${s.status}\n\n**Problem:** ${s.problem}\n\n**Gates:**\n${gates.map((g) => `- [${g.ok ? 'x' : ' '}] ${g.label}: ${g.detail}`).join('\n')}\n\n**Acceptance criteria:**\n${s.acceptance.map((a) => `- ${a}`).join('\n')}`;
}
