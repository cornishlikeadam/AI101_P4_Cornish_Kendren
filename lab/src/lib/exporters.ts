/* Markdown and JSON exporters. Every export keeps source attribution and the approval state of each
   decision, and says plainly when something is unapproved or unknown. */
import type { Character, DesignDecision, ImageRef, Issue, Scene, SceneIteration, ScreenshotComparison, Sprint, Workspace } from '../types';
import { QC_CATEGORIES, RUBRIC } from '../types';
import { snapshot } from '../seed/snapshot';
import { reviewResult, sprintGates } from './readiness';
import { mdEscape } from './util';

const ref = (r: ImageRef | null | undefined) => (!r ? '_none_' : r.kind === 'evidence' ? '`' + r.path + '`' : `uploaded file "${r.name ?? r.id}" (lab IndexedDB, not in the repository)`);
const list = (xs: string[]) => (xs.length ? xs.map((x) => `- ${x}`).join('\n') : '- _none recorded_');
const approval = (d: DesignDecision) => d.workflow === 'Approved' ? `Approved${d.history.filter((h) => h.action === 'Approved').slice(-1).map((h) => ` by ${h.by} on ${h.at.slice(0, 10)}`).join('')}` : `${d.workflow} (not approved)`;

export function nextAdrNumber(ws: Workspace) {
  const repo = (snapshot.docs ?? []).map((d) => d.path.match(/ADR-(\d{3})/)?.[1]).filter(Boolean).map(Number);
  const used = Object.values(ws.decisions).map((d) => d.code.match(/^ADR-(\d{3})$/)?.[1]).filter(Boolean).map(Number);
  return Math.max(2, ...repo, ...used) + 1;
}

export function decisionAdr(ws: Workspace, d: DesignDecision, number: number) {
  const n = String(number).padStart(3, '0');
  const sup = d.supersedes ? (ws.decisions[d.supersedes]?.code ?? d.supersedes) : 'nothing';
  return `# ADR-${n}: ${d.title}

**Status:** ${approval(d)}
**Lab record:** ${d.code} (${d.lineage}, verification: ${d.status})
**Date exported:** ${new Date().toISOString().slice(0, 10)}
**Supersedes:** ${sup}. The original rule is quoted below and the earlier ADR file is left unchanged.
**Owner:** ${d.owner || '_unassigned_'}

## Original rule

${d.originalRule || '_not recorded_'}

## Decision

${d.workflow === 'Approved' ? (d.currentApproved ?? d.proposedReplacement) : `_Proposed, not approved:_ ${d.proposedReplacement}`}

## Rationale

${d.rationale || '_not recorded_'}

## Evidence (${d.evidenceType})

${d.evidence || '_none_'}

Source: ${d.sourceRef || '_none_'}

## Expected effect and cost

- Visual: ${d.expectedVisual || '_unknown_'}
- Technical cost: ${d.expectedCost || '_unknown_'}
- Compatibility: ${d.compatibility || '_unknown_'}

## Related

Files:
${list(d.relatedFiles.map((f) => '`' + f + '`'))}

Tests that must pass:
${list(d.tests)}

Issues: ${d.issueIds.map((i) => ws.issues[i]?.code ?? i).join(', ') || '_none_'} · Sprints: ${d.sprintIds.map((i) => ws.sprints[i]?.code ?? i).join(', ') || '_none_'}

## Decision history

${d.history.map((h) => `- ${h.at.slice(0, 16).replace('T', ' ')} · ${h.action} by ${h.by}${h.note ? ': ' + h.note : ''}`).join('\n')}
`;
}

/** Combined ADR for every approved decision (the "illustrated scene pipeline" ADR the brief asks for). */
export function pipelineAdr(ws: Workspace) {
  const n = String(nextAdrNumber(ws)).padStart(3, '0');
  const ds = Object.values(ws.decisions).sort((a, b) => a.priority - b.priority);
  const approved = ds.filter((d) => d.workflow === 'Approved');
  return `# ADR-${n}: Illustrated scene pipeline

**Status:** ${approved.length ? `${approved.length} of ${ds.length} lab decisions approved` : 'Draft: no lab decision is approved yet'}
**Relationship:** Builds on ADR-002 (illustrated world) and supersedes the parts of ADR-001 listed below. ADR-001 and ADR-002 are not edited.
**Generated by:** Waldo's Savannah Build Lab, ${new Date().toISOString().slice(0, 10)}

| Rule | Original (ADR-001) | Decision | State |
|---|---|---|---|
${ds.map((d) => `| ${d.code} ${mdEscape(d.title)} | ${mdEscape(d.originalRule)} | ${mdEscape(d.workflow === 'Approved' ? d.currentApproved ?? d.proposedReplacement : d.proposedReplacement)} | ${approval(d)} |`).join('\n')}

${ds.map((d) => `## ${d.code}: ${d.title}\n\n${d.rationale}\n\nEvidence: ${d.evidence}\n\nSource: ${d.sourceRef}`).join('\n\n')}
`;
}

