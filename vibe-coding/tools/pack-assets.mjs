// Packs every SVG under vibe-coding/assets/ into build/js/assets.bundle.js, a classic script
// that works when index.html is opened from disk (file://) as well as over HTTP.
// usage: node vibe-coding/tools/pack-assets.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ART_VERSION = 1;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = join(root, 'assets');
const out = join(root, 'build', 'js', 'assets.bundle.js');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.svg') ? [p] : [];
  });
}

const STRAIGHT_H = /^M-?\d+(?:\.\d+)?,(-?\d+(?:\.\d+)?)\s*H-?\d+(?:\.\d+)?$/;
const STRAIGHT_HV = /^M-?\d+(?:\.\d+)?[,\s]-?\d+(?:\.\d+)?\s*[HVhv]-?\d+(?:\.\d+)?$/;
const UNSAFE_ATTR = /\b(?:id|clip-path|mask|transform|marker-|stroke-dasharray|stroke-dashoffset|opacity|data-)=/;
const SEM_OPACITY = /\bstroke-opacity=/;
function compactSvg(s) {
  s = s.replace(/>\s+</g, '><').trim();
  const re = /<path d="([^"]+)"((?:\s+[a-zA-Z0-9:-]+="[^"]*")*)\s*\/>/g;
  let out = '', lastIdx = 0, runD = [], runAttr = null, runYs = null;
  const flush = () => {
    if (runD.length) { out += `<path d="${runD.join(' ').replace(/ ([MLHVmlhv])/g, '$1')}"${runAttr}/>`; runD = []; runAttr = null; runYs = null; }
  };
  for (let m; (m = re.exec(s)); ) {
    if (m.index > lastIdx) { flush(); out += s.slice(lastIdx, m.index); }
    const [, d, attrs] = m;
    const noUnsafe = !UNSAFE_ATTR.test(attrs);
    const hasAlpha = SEM_OPACITY.test(attrs);
    const hMatch = STRAIGHT_H.exec(d);
    const unfilled = /\bfill="none"/.test(attrs) || (STRAIGHT_HV.test(d) && !/\bfill=/.test(attrs));
    const ok = noUnsafe && unfilled && (!hasAlpha || hMatch);
    if (ok && attrs === runAttr && (!hasAlpha || (hMatch && !runYs.has(hMatch[1])))) {
      runD.push(d);
      if (runYs && hMatch) runYs.add(hMatch[1]);
    } else {
      flush();
      if (ok) { runD = [d]; runAttr = attrs; runYs = hasAlpha && hMatch ? new Set([hMatch[1]]) : null; }
      else out += m[0];
    }
    lastIdx = re.lastIndex;
  }
  flush();
  return out + s.slice(lastIdx);
}

const svg = {}, meta = {};
for (const file of walk(assetsDir)) {
  const id = relative(assetsDir, file).replace(/\\/g, '/').replace(/\.svg$/, '');
  const text = compactSvg(readFileSync(file, 'utf8'));
  const head = /<svg[^>]*>/.exec(text)[0];
  const attr = (name) => (new RegExp(`${name}="([^"]+)"`).exec(head) || [])[1];
  const vb = attr('viewBox').split(/\s+/).map(Number);
  const nums = (v) => (v ? v.split(/\s+/).map(Number) : null);
  svg[id] = text;
  meta[id] = {
    viewBox: vb,
    anchor: nums(attr('data-anchor')) || [vb[0] + vb[2] / 2, vb[1] + vb[3]],
    hand: nums(attr('data-hand')),
    collar: nums(attr('data-collar')),
    layer: attr('data-layer') || 'world',
    slots: (attr('data-slots') || '').split(/\s+/).filter(Boolean),
    traits: (attr('data-traits') || '').split(/\s+/).filter(Boolean),
    head: nums(attr('data-head')),
    seat: nums(attr('data-seat')),
    part: attr('data-part') || null,
    hats: attr('data-hats') ? attr('data-hats').split(/\s+/) : null,
    head2: nums(attr('data-head2')),
    kit: attr('data-kit') || null,
    kit2: attr('data-kit2') || null,
    frames: text.includes('data-frame="2"') ? 2 : 1,
    author: attr('data-author') || null,
  };
}

mkdirSync(dirname(out), { recursive: true });
const body = `/* Generated by tools/pack-assets.mjs. Do not edit; edit vibe-coding/assets/ and re-run. */\nwindow.WS_ASSETS = ${JSON.stringify({ artVersion: ART_VERSION, svg, meta })};\n`;
writeFileSync(out, body);
console.log(`packed ${Object.keys(svg).length} assets, ${(body.length / 1024).toFixed(1)} KB -> ${relative(root, out)}`);
