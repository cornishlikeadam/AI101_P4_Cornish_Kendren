// Builds the illustrated game: packs assets, then joins the classic-script sources in src/ into
// build/js/game.js. No bundler and no modules, so build/index.html also runs from file://.
// usage: node vibe-coding/tools/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
execFileSync(process.execPath, [join(root, 'tools', 'pack-assets.mjs')], { stdio: 'inherit' });
const ORDER = [
  'utilities/rng.js',
  'characters/compose.js', 'characters/make.js',
  'scenes/forsyth.js',
  'engine/sprites.js', 'engine/engine.js', 'engine/input.js',
  'gameplay/round.js', 'gameplay/leaderboard.js',
  'main.js',
];
const out = ORDER.map((f) => `/* ---- src/${f} ---- */\n` + readFileSync(join(root, 'src', f), 'utf8')).join('\n');
writeFileSync(join(root, 'build', 'js', 'game.js'), `/* Generated by tools/build.mjs from vibe-coding/src/. Do not edit. */\n${out}`);
console.log(`built build/js/game.js from ${ORDER.length} sources, ${(out.length / 1024).toFixed(1)} KB`);
