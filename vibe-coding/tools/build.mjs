// Builds the illustrated game: packs assets and joins the classic-script sources in src/ inline
// into a single self-contained build/index.html (runs from file:// and over HTTP).
// usage: node vibe-coding/tools/build.mjs
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { packAssets } from './pack-assets.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { count, body: assetsBody } = packAssets();
const ORDER = [
  'utilities/rng.js',
  'characters/compose.js', 'characters/make.js',
  'scenes/build.js', 'scenes/streets.js', 'scenes/forsyth.js', 'scenes/riverfront.js', 'scenes/market.js', 'scenes/squares.js', 'scenes/monterey.js', 'scenes/wings.js', 'scenes/savannah.js',
  'engine/sprites.js', 'engine/engine.js', 'engine/input.js',
  'gameplay/round.js', 'gameplay/leaderboard.js',
  'main.js',
];
const gameBody = `/* Generated by tools/build.mjs from vibe-coding/src/. Do not edit. */\n` +
  ORDER.map((f) => `/* ---- src/${f} ---- */\n` + readFileSync(join(root, 'src', f), 'utf8')).join('\n');

const escapeScript = (js) => js.replace(/<\/(script)/gi, '<\\/$1');
const template = readFileSync(join(root, 'src', 'index.html'), 'utf8');
const marker = '<!-- WS_INLINE_SCRIPTS -->';
if (!template.includes(marker)) throw new Error('Missing WS_INLINE_SCRIPTS marker in src/index.html');
const html = template.replace(
  marker,
  () => `<script>\n${escapeScript(assetsBody)}</script>\n<script>\n${escapeScript(gameBody)}</script>`
);

rmSync(join(root, 'build', 'js'), { recursive: true, force: true });
writeFileSync(join(root, 'build', 'index.html'), html);
console.log(`packed ${count} assets (${(assetsBody.length / 1024).toFixed(1)} KB) + ${ORDER.length} sources (${(gameBody.length / 1024).toFixed(1)} KB) -> build/index.html (${(html.length / 1024).toFixed(1)} KB)`);
